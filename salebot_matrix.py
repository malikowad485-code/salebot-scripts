def validate_date(raw):
    if not raw:
        return {"date_valid": False, "date_reason": "пустая строка"}

    match = re.match(r'^(\d{1,2})[\.\/\-\s](\d{1,2})[\.\/\-\s](\d{2,4})$', str(raw).strip())
    if not match:
        return {"date_valid": False, "date_reason": "неверный формат"}

    day, month, year = map(int, match.groups())
    if year < 100:
        year = 2000 + year if year <= 29 else 1900 + year

    current_year = datetime.now().year
    if year < 1920 or year > current_year:
        return {"date_valid": False, "date_reason": f"год вне диапазона 1920-{current_year}"}

    try:
        dt = datetime(year, month, day)
    except ValueError:
        return {"date_valid": False, "date_reason": "такой даты не существует"}

    return {
        "date_valid": True,
        "date_formatted": dt.strftime("%d.%m.%Y"),
        "day": day, "month": month, "year": year
    }

def reduce_value(value):
    while value > 22:
        value -= 22
    return value

def sum_digits(number):
    return sum(int(digit) for digit in str(number))

def calculate_matrix(day, month, year):
    a = reduce_value(day)
    b = reduce_value(month)
    c = reduce_value(sum_digits(year))
    d = reduce_value(a + c)
    x = reduce_value(a + b)
    y = reduce_value(d + x)
    z = reduce_value(d + a)
    f = reduce_value(x + a)
    k = reduce_value(c + b)
    e = reduce_value(k + d)
    n = reduce_value(k + c)
    m = reduce_value(c + d)
    v = reduce_value(k + x)
    l = reduce_value(k + b)
    h = reduce_value(b + x)
    r1 = reduce_value(z + y + f)
    r2 = reduce_value(m + e + n)
    r3 = reduce_value(h + l + v)
    r4 = reduce_value(r1 + r2 + r3)
    return {"a":a,"b":b,"c":c,"d":d,"e":e,"m":m,"n":n,"v":v,"h":h,"l":l,"k":k,"z":z,"y":y,"x":x,"f":f,"R1":r1,"R2":r2,"R3":r3,"R4":r4}

def handle(data):
    if isinstance(data, str):
        try:
            data = json.loads(data)
        except (json.JSONDecodeError, TypeError):
            return json.dumps({"date_valid": False, "date_reason": "не удалось разобрать входные параметры"}, ensure_ascii=False)

    raw_date = data.get("date", "")
    result = validate_date(raw_date)
