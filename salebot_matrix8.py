def validate_date(raw):
    """Проверяет дату в форматах ДД.ММ.ГГГГ, ДД/ММ/ГГГГ, ДД-ММ-ГГГГ, ДД ММ ГГГГ."""
    if not raw:
        return {"date_valid": False, "date_reason": "пустая строка"}

    match = re.match(
        r'^(\d{1,2})[\.\/\-\s](\d{1,2})[\.\/\-\s](\d{2,4})$',
        str(raw).strip()
    )
    if not match:
        return {"date_valid": False, "date_reason": "неверный формат"}

    day, month, year = match.groups()
    day, month, year = int(day), int(month), int(year)

    if year < 100:
        year = 2000 + year if year <= 29 else 1900 + year

    current_year = datetime.now().year
    if year < 1920 or year > current_year:
        return {"date_valid": False, "date_reason": f"год вне диапазона 1920-{current_year}"}

    try:
        dt = datetime(year, month, day)
    except ValueError:
        return {"date_valid": False, "date_reason": "такой даты не существует"}

    return {
        "date_valid": True,
        "date_formatted": dt.strftime("%d.%m.%Y"),
        "day": day,
        "month": month,
        "year": year
    }


def reduce_value(value):
    """Приводит значение к диапазону 1-22, вычитая 22 пока значение больше 22."""
    while value > 22:
        value -= 22
    return value


def sum_digits(number):
    """Складывает все цифры числа (например, 1983 -> 1+9+8+3=21)."""
    return sum(int(digit) for digit in str(number))


def calculate_matrix(day, month, year):
    """Считает все ключевые точки матрицы, 9 сценариев, Архетипы Уровня 1, типы Масок и PALMS 2.0."""
    a = reduce_value(day)
    b = reduce_value(month)
    c = reduce_value(sum_digits(year))

    d = reduce_value(a + c)
    x = reduce_value(a + b)
    y = reduce_value(d + x)
    z = reduce_value(d + a)
    f = reduce_value(x + a)
    k = reduce_value(c + b)
    e = reduce_value(k + d)
    n = reduce_value(k + c)
    m = reduce_value(c + d)
    v = reduce_value(k + x)
    l = reduce_value(k + b)
    h = reduce_value(b + x)

    r1 = reduce_value(z + y + f)
    r2 = reduce_value(m + e + n)
    r3 = reduce_value(h + l + v)
    r4 = reduce_value(r1 + r2 + r3)

    # Названия архетипов (только для Уровня 1: Центры Души и Альтер-эго)
    arch_nodes = {"a": a, "b": b, "c": c, "d": d, "k": k, "x": x}
    arch_names = {f"{key}_arch": ARCHETYPES.get(val, "") for key, val in arch_nodes.items()}

    # Точные канонические типы Масок (Уровень 2)
    mask_nodes = {"y": y, "z": z, "e": e, "n": n, "m": m, "f": f, "h": h, "v": v, "l": l}
    mask_types = {f"{key}_type": MASK_TYPES.get(val, "") for key, val in mask_nodes.items()}

    # Точные травмы для Теней и Типажа (Уровень 3)
    r_nodes = {"R1": r1, "R2": r2, "R3": r3, "R4": r4}
    traumas = {}
    for key, val in r_nodes.items():
        info = PALMS_DATA.get(val, {})
        traumas[f"{key}_trauma"] = info.get("trauma", "")

    # Готовый блок для протокола PALMS 2.0 (последовательно уникальные ключи из R1, R2, R3, R4)
    unique_keys = []
    for val in [r1, r2, r3, r4]:
        if val not in unique_keys:
            unique_keys.append(val)

    palms_points_list = []
    for val in unique_keys:
        info = PALMS_DATA.get(val)
        if info:
            palms_points_list.append(
                f"**Ключ {val} ({info['trauma']}):**\n\n"
                f"* **Зона наложения ладони:** {info['location']}.\n\n"
                f"* **Соматическое микродействие:** {info['somatic']}\n\n"
                f"* **Текст смыслового растождествления:** «{info['meditation']}»"
            )
